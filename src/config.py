# ---------------------------------------------------------------------------
# 角度映射（唯一实现处，界面 / 控制层 / 视图都调这里，避免各处各写一遍取反）
# ---------------------------------------------------------------------------
def view_angle(servo_angle):
    """舵机角 → **观察角**：0 = 左，90 = 正前方，180 = 右。

    扇区判定、扫描图的横轴、界面上的角度都统一用观察角，因此装上舵机后若发现
    左右相反，只需把 ``SERVO_INVERT`` 置 True —— 脉宽标定不受影响。

    界面上只暴露观察角（用户关心的是"探头朝哪边"），舵机角只在驱动层与日志里
    出现；两者互转就用本函数与 ``servo_angle``。
    """
    deg = max(SERVO_ANGLE_MIN, min(SERVO_ANGLE_MAX, float(servo_angle)))
    return (SERVO_ANGLE_MAX + SERVO_ANGLE_MIN) - deg if SERVO_INVERT else deg


def servo_angle(view_deg):
    """观察角 → 舵机角。

    本映射是**自逆**的（要么恒等、要么 180-x，做两次就回到原值），所以两个方向
    用同一套算法；分开命名只是让调用处读得懂"现在转的是哪一侧的角"。
    """
    return view_angle(view_deg)


def sector_of(view_deg):
    """观察角 → 扇区名（``"Left"`` / ``"Center"`` / ``"Right"``）。

    边界归前一个扇区（60.0 属 Center、120.0 属 Right），保证任意角度只落一个扇区。
    直接遍历 ``SECTORS``：以后加扇区不用改这里，也不用去改扫描图里的标签。
    """
    deg = float(view_deg)
    for name, (_lo, hi) in SECTORS:
        if deg <= hi:
            return name
    return SECTORS[-1][0]
