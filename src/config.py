# ---------------------------------------------------------------------------
# US01 寄存器与命令（模块使用手册 V1.0）
# ---------------------------------------------------------------------------
REG_R_RED, REG_R_GREEN, REG_R_BLUE = 0x00, 0x01, 0x02   # R 探头（接收）
REG_T_RED, REG_T_GREEN, REG_T_BLUE = 0x03, 0x04, 0x05   # T 探头（发射）
REG_CMD = 0x10                                          # 命令寄存器
CMD_START_MEASURE = 0x01                                # 启动一次测距

MEASURE_WAIT_S = 0.10       # 写命令后到可读结果的最小等待（手册周期 50ms，实测约 160ms）
REG_WRITE_GAP_S = 0.001     # 相邻 RGB 寄存器写入之间的间隔（对齐官方例程 delay(1)）
RETRY = 3                   # 单次 I2C 读写失败的重试次数

# raw==0（模块这次没给出结果）时的**立刻重读**次数。
# 实测（交错采样对比 0/1/2 次重读，各 60 次）：有效率 93.3% → 95.0% → 93.3%，
# 平均单次耗时 101ms → 107ms → 116ms —— 平时帮助有限、代价也小；
# 但在模块"成片丢点"的坏窗口里（实测出现过连续 46 次 raw=0），重读能救回约 85%。
# 因此保留 1 次作兜底；0 = 关闭。
# 另做过"命令后等多久"的扫参（0.10/0.12/0.15/0.18/0.22/0.30s），有效率**并非单调改善**
# （0.10s 与 0.30s 是 20/20，中间几档只有 8~9/20），所以单靠调等待时长治不好。
NO_ECHO_RETRY = 1

# ---------------------------------------------------------------------------
# 量程与换算
# ---------------------------------------------------------------------------
RAW_TO_CM = 0.017           # raw(回波时间 us) → 距离 cm（声速 340m/s 折半）
DIST_MIN_CM = 2.0           # 盲区下限
DIST_MAX_CM = 400.0         # 量程上限

# ---------------------------------------------------------------------------
# 采集与判定
# ---------------------------------------------------------------------------
POLL_HZ = 5.0               # 目标刷新率（受"单次测量 ≥100ms"物理限制）
MEDIAN_WINDOW = 3           # 滑动中值窗口点数（抑制偶发野值）
OUTLIER_LOG_CM = 5.0        # 原始值与中值之差超过此值时记一条日志
HISTORY_GAP_BRIDGE = 2      # 历史曲线最多跨几个丢点画虚线（0 = 一律断开）

# 丢点保持：模块本身有 5~7% 的偶发丢点（实测，重读也救不回来），5Hz 下约每 3~4 秒
# 闪一次。连续丢点少于该值时，界面**保持上次读数**并把状态标成"保持"，
# 而不是立刻闪成 `--.-`；连续丢到该值才认为真丢了信号。
# 曲线始终只画真实测到的点，不受此影响（保持值绝不进曲线，避免画出没测过的距离）。
# 0 = 关闭保持（恢复"一丢点就显示 --.-"）。
HOLD_FAILS = 3

DEFAULT_RANGE_CM = 50.0     # 默认探测范围（界面滑块初值）
HYSTERESIS_CM = 2.0         # 退出判定的回滞量，防止阈值边缘来回抖动
RANGE_MIN_CM = 5.0          # 探测范围可调下限
RANGE_MAX_CM = 200.0        # 探测范围可调上限

# ---------------------------------------------------------------------------
# 仿真（在没有 /dev/i2c-N 的开发机上让界面与逻辑可以完整演示）
# ---------------------------------------------------------------------------
SIM_SHOT_S = 0.16           # 仿真单次耗时，刻意对齐真机节拍
SIM_NEAR_CM = 10.0          # 仿真最近点
SIM_FAR_CM = 100.0          # 仿真最远点
SIM_PERIOD_S = 14.0         # 仿真往返周期

# 仿真扫描：在 SIM_TARGET_DEG 方位摆一个物体，其余方向当作远背景墙。
# 只为"没有硬件时也能看到左中右判定"，不影响真机行为。
SIM_TARGET_DEG = 35.0       # 物体所在观察角（默认 35° = 左侧）
SIM_TARGET_CM = 28.0        # 物体距离
SIM_TARGET_WIDTH_DEG = 12.0 # 物体在角度上的张角（半宽）
SIM_BACK_CM = 140.0         # 背景墙距离（默认超出阈值，因此不会干扰判定）

# ---------------------------------------------------------------------------
# 舵机（板载 PWM2_CH3 = 40-Pin Pin33，走内核 sysfs /sys/class/pwm）
# ---------------------------------------------------------------------------
# 为什么走 sysfs：内核已经把 PWM 控制器暴露成"写两个文件"，
# 写 period / duty_cycle 就是硬件 PWM（无软件抖动），且不需要任何新依赖。
PWM_CHIP_DEVICE = "2ade3000.pwm"    # PWM 控制器设备名。用它在 /sys/class/pwm 里
                                    # 认芯片而不写死 pwmchipN —— 重启后编号可能变
PWM_CHANNEL = 0                     # 该控制器只暴露 1 个通道（= PWM2_CH3）
PWM_FREQ_HZ = 50.0                  # 舵机工作频率（周期 20ms）
PWM_EXPORT_WAIT_S = 0.05            # export 后等待 sysfs 建出 pwmN 目录的轮询间隔
# 极性：舵机要的是**正相**脉冲（周期内大部分时间为低，脉宽期间为高）。
# 本板 2ade3000.pwm 导出后默认是 "inversed"（反相），必须显式纠正，
# 否则舵机收到的是低电平脉冲，表现为不动 / 乱抖 / 冲到底。
PWM_POLARITY = "normal"             # "normal" 正相 / "inversed" 反相

SERVO_PULSE_MIN_US = 500.0          # 0°   对应脉宽
SERVO_PULSE_MAX_US = 2500.0         # 180° 对应脉宽
SERVO_ANGLE_MIN = 0.0               # 机械行程下限（舵机角）
SERVO_ANGLE_MAX = 180.0             # 机械行程上限（舵机角）
SERVO_TRIM_DEG = 0.0                # 中位装配偏差补偿（正值 = 整体往大角度方向偏）
# ---------------------------------------------------------------------------
# 运动平滑（梯形速度斜坡）
# ---------------------------------------------------------------------------
# 为什么需要：PWM 舵机是"写一次即瞬变"的硬件，没有片上缓动。若把目标角一次写下去，
# 从停靠位 90° 跳到扫描起点 0° 就是**位置阶跃** —— 舵机内部控制器全速冲刺，
# 齿轮撞击声很大、电流尖峰明显（共用电源时还会拖累超声模块）。
# 这里按"角加速度受限 → 匀速 → 减速到位"把一个大角度拆成几十次小步下发，
# 舵机会平滑地跟着走，落位时速度已接近 0，也就不需要很长的稳定等待。
# 小步移动（扫描每步 5°）只会走一小段三角形曲线，耗时可忽略。
SERVO_SLEW_DPS = 240.0              # 巡航角速度上限（度/秒）；0 = 关闭斜坡（恢复瞬变）
SERVO_SLEW_ACCEL_DPS2 = 4800.0      # 角加速度上限（度/秒²）；0 = 匀速（只有速度阶跃）
SERVO_SLEW_TICK_S = 0.01            # 斜坡刷新周期（10ms → 100 次/秒）
# 左右映射：2026-10-15 实机标定 —— 装上后画面是"左→右"扫、实物是"右→左"扫，
# 即观察角与实际朝向镜像，故置 True。
# 它只翻转"0° 算左还是算右"的解释（config.view_angle），脉宽/行程标定一概不动；
# 停靠角 90° 是中位，翻转前后都是正前方，不受影响。
SERVO_INVERT = True
SERVO_SETTLE_S = 0.12               # 下发角度后等待机械稳定（有斜坡后落位速度已接近 0，
                                    # 比"瞬变 + 长等待"更稳也更省时间）
SERVO_PARK_DEG = 90.0               # 不扫描时的停靠角（90 = 正前方）
SERVO_RELEASE_ON_EXIT = False       # True = 退出即关 PWM（舵机掉力）；False = 保持停靠角

